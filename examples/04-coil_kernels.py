from pathlib import Path
from urllib.request import urlretrieve

import matplotlib.pyplot as plt
import numpy as np
import torch

import mrtoeplitz as mt

# Three sensitivity banks, all produced by BART rather than by hand, and
# regenerated by examples/make_coil_maps.sh:
#
#   simulated : bart coils --H2D8C, its own analytic 8-channel head coil
#   espirit   : bart ecalib, eigenvector-normalised
#   nlinv     : bart nlinv, whose Sobolev weighting is a band limit
local = Path("coil_maps.npz")
if not local.exists():
    urlretrieve(
        "https://raw.githubusercontent.com/FiRMLAB-Pisa/mrtoeplitz/main/"
        "examples/coil_maps.npz",
        local,
    )
loaded = np.load(local)
banks = {
    name: torch.as_tensor(loaded[name]) for name in ("simulated", "espirit", "nlinv")
}
image = torch.as_tensor(loaded["object"]).to(torch.complex64)
n = image.shape[-1]
print({name: tuple(bank.shape) for name, bank in banks.items()})

# %% [markdown]
# ## The kernel is the native form
#
# A sensitivity is smooth. That is not a hope about it — it is why a calibration
# can be solved on a low-resolution ACS region at all, and why NLINV can impose
# a Sobolev weighting and still fit the data. What such a solver produces is a
# small array of k-space coefficients. The dense map is what you get by
# zero-padding that array to the image grid and transforming it.
#
# So the map is the derived object, and forming it is a choice: at 320 cubed
# with 48 channels it costs 12.6 GB, which on most cards *is* the
# reconstruction. `CoilKernels` holds the coefficients instead and defers the
# padding to whichever coils a call actually asks for — which a SENSE normal
# already reads one batch at a time.
#
# Nothing is approximated by this. There is no truncation error to weigh,
# because nothing has been truncated.

# %%
# What a calibration actually solves for. NLINV's Sobolev weighting is a band
# limit, so its unknown *is* a small set of k-space coefficients; the dense map
# is that array zero-padded to the image grid and transformed. Here the
# coefficients are recovered from BART's maps, because its CLI hands back the
# padded form -- in a pipeline they come straight off the solver and the map is
# never formed at all.
coefficients = np.fft.fftshift(
    np.fft.fftn(np.fft.ifftshift(banks["nlinv"].numpy(), axes=(-2, -1)), axes=(-2, -1)),
    axes=(-2, -1),
)
side = 12
centre = n // 2
calibration = torch.as_tensor(
    coefficients[
        :,
        centre - side // 2 : centre + side // 2,
        centre - side // 2 : centre + side // 2,
    ].astype(np.complex64)
)
print(f"the calibration's unknown: {tuple(calibration.shape)}")

# Held as it came. No truncation decision arises, because nothing was
# truncated: the padding is simply deferred.
coil_kernels = mt.CoilKernels(calibration, (n, n))
print(coil_kernels)
print(
    f"{coil_kernels.storage_nbytes / 2**10:.1f} KiB held against "
    f"{coil_kernels.dense_nbytes / 2**10:.0f} KiB of maps"
)

# %% [markdown]
# ## In the normal operator
#
# `apply_sense` takes either a tensor or a `CoilKernels`, and nothing else in a
# solve changes.

# %%
angles = np.linspace(0, np.pi, 96, endpoint=False)
radius = np.linspace(-0.5, 0.5, 192, endpoint=False)
trajectory = np.stack(
    [np.outer(np.cos(angles), radius), np.outer(np.sin(angles), radius)], axis=-1
).astype(np.float32)
density = np.linalg.norm(trajectory, axis=-1).astype(np.float32)
kernel = mt.scalar_kernel(trajectory, (n, n), density=density)

through_maps = mt.apply_sense(kernel, image[None, None], banks["nlinv"])
through_kernels = mt.apply_sense(kernel, image[None, None], coil_kernels)
agreement = float((through_maps - through_kernels).norm() / through_maps.norm())
print(f"SENSE normal through maps and through coil kernels agree to {agreement:.1e}")

# %% [markdown]
# ## If you were handed dense maps instead
#
# Sometimes the coefficients are gone and only the maps remain. Then the
# question is whether the bank can be reduced to a kernel after the fact, and
# that is a measurement — `tolerance` finds the smallest kernel that holds the
# bank to it, reading the error off the spectrum by Parseval rather than
# expanding a candidate.
#
# The three banks below say how far that gets, and it is a good illustration of
# what breaks smoothness: not the physics, but what is done to a map after it is
# estimated.

# %%
sides = (4, 8, 12, 16, 24, 32, 48, 64)
errors = {
    name: [
        float(mt.CoilKernels.from_maps(bank, (k, k)).truncation_error(bank))
        for k in sides
    ]
    for name, bank in banks.items()
}

print(f"{'kernel side':>12}" + "".join(f"{name:>12}" for name in banks))
for index, k in enumerate(sides):
    print(f"{k:>12}" + "".join(f"{errors[name][index]:>12.1e}" for name in banks))

# %%
fig, axes = plt.subplots(1, 4, figsize=(13, 3.2))
for axis, (name, bank) in zip(axes[:3], banks.items(), strict=True):
    axis.imshow(np.abs(bank[0].numpy()), cmap="viridis")
    axis.set_title(f"{name}, coil 0")
    axis.set_xticks([])
    axis.set_yticks([])

for name in banks:
    axes[3].semilogy(sides, errors[name], "o-", markersize=3, label=name)
axes[3].set_title("truncation error")
axes[3].set_xlabel("kernel side")
axes[3].legend(fontsize=8)
fig.tight_layout()

