# %%
# Asking for a tolerance rather than a size: the kernel is measured from the
# spectrum by Parseval, which costs one transform however many sizes it
# considers -- and a bank with no such kernel is refused rather than quietly
# truncated.
for name, bank in banks.items():
    try:
        chosen = mt.CoilKernels.from_maps(bank, tolerance=1e-3)
        print(
            f"{name:>10}: K={chosen.kernel_shape[0]:3d}, "
            f"{chosen.compression_ratio:5.0f}x smaller, "
            f"error {chosen.truncation_error(bank):.1e}"
        )
    except ValueError as refusal:
        print(f"{name:>10}: refused -- {str(refusal).split(';')[1].strip()}")


# %% [markdown]
# NLINV's maps reduce almost to nothing, which is expected: they were a
# kernel to begin with. ESPIRiT's barely reduce — the `|m| = 1` eigenvector
# normalisation puts a hard edge in the image, and a hard edge has broad k-space
# support, so what is lost is the normalisation's doing rather than the
# sensitivity's. For ESPIRiT the answer is the same as for NLINV: keep the
# calibration kernels and never form the map.
#
# A simulated array is refused outright. Its maps are an analytic field
# evaluated on the grid rather than anything a calibration produced, and a field
# from a conductor decays as a power law.


# %%
def spectrum(bank):
    axes_ = (-2, -1)
    return np.abs(
        np.fft.fftshift(
            np.fft.fftn(np.fft.ifftshift(bank[0].numpy(), axes=axes_), axes=axes_),
            axes=axes_,
        )
    )


fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.4))
middle = n // 2
for name, bank in banks.items():
    profile = spectrum(bank)[middle]
    axes[0].semilogy(np.arange(n) - middle, profile / profile.max(), label=name)
axes[0].set_xlim(-48, 48)
axes[0].set_ylim(1e-9, 2)
axes[0].set_title("k-space of one map")
axes[0].set_xlabel("k")
axes[0].legend(fontsize=8)

for name, bank in banks.items():
    power = spectrum(bank) ** 2
    kept = [
        power[
            middle - k // 2 : middle - k // 2 + k, middle - k // 2 : middle - k // 2 + k
        ].sum()
        / power.sum()
        for k in sides
    ]
    axes[1].semilogy(sides, 1.0 - np.array(kept), "o-", markersize=3, label=name)
axes[1].set_title("energy left outside the kernel")
axes[1].set_xlabel("kernel side")
axes[1].legend(fontsize=8)
fig.tight_layout()

# %% [markdown]
# ## Where it matters
#
# The kernel is set by how smooth the sensitivity is, not by the image, so the
# saving grows with the volume.

# %%
print(f"{'grid':>18}  {'maps':>10}  {'coil kernels':>13}   ratio")
for shape, coils in (((128, 128), 8), ((256, 256, 256), 32), ((320, 320, 320), 48)):
    dense = coils * int(np.prod(shape)) * 8
    kept = coils * side ** len(shape) * 8
    label = "x".join(str(s) for s in shape) + f" x {coils}"
    print(
        f"{label:>18}  {dense / 2**30:8.2f} GB  {kept / 2**20:9.2f} MB  "
        f"{dense / kept:6.0f}x"
    )
